alter table public.model_providers
  add column sort_order integer generated by default as identity;

-- Keep the original creation order until an administrator reorders the list.
with positions as (
  select id, row_number() over (order by created_at, id)::integer as position
  from public.model_providers
)
update public.model_providers as provider
set sort_order = positions.position
from positions
where provider.id = positions.id;

select setval(
  pg_get_serial_sequence('public.model_providers', 'sort_order'),
  coalesce((select max(sort_order) from public.model_providers), 0) + 1,
  false
);

create function public.reorder_model_providers(p_provider_ids uuid[])
returns void language plpgsql security invoker set search_path = '' as $$
begin
  -- Serialize the short batch update with provider creation and other reorders.
  lock table public.model_providers in share row exclusive mode;
  if p_provider_ids is null
    or coalesce(array_ndims(p_provider_ids), 0) <> 1
    or cardinality(p_provider_ids) = 0
    or cardinality(p_provider_ids) <> (select count(distinct id) from unnest(p_provider_ids) as ids(id))
    or exists(select id from public.model_providers except select unnest(p_provider_ids))
    or exists(select unnest(p_provider_ids) except select id from public.model_providers)
  then
    raise exception 'provider_list_changed' using errcode = 'P0001';
  end if;

  update public.model_providers as provider
  set sort_order = positions.position
  from unnest(p_provider_ids) with ordinality as positions(id, position)
  where provider.id = positions.id;
end;
$$;

revoke all on function public.reorder_model_providers(uuid[]) from public, anon, authenticated;
grant execute on function public.reorder_model_providers(uuid[]) to service_role;

notify pgrst, 'reload schema';
